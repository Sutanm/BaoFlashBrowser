// Builds the core-js page-world polyfill bundle (C87 lacks modern Web APIs;
// a missing API crashes whole site bundles — GitHub needed randomUUID and
// .at() separately). Selected core-js modules are bundled to a single IIFE
// and emitted as a TS string module embedded into webview-preload, which
// injects it into the PAGE main world at document-start via
// webFrame.executeJavaScript.
import esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '..', 'src', 'webview-preload', 'web-api-polyfills.generated.ts');

const result = await esbuild.build({
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: 'chrome87',
  minify: true,
  entryPoints: ['src/webview-preload/web-api-polyfills-entry.ts'],
  write: false,
});
const code = result.outputFiles[0].text;
const generated = `// GENERATED by scripts/build-web-polyfills.mjs — do not edit.
// core-js selected modules, injected into the page main world.
export default ${JSON.stringify(code)};\n`;

let current = '';
try { current = fs.readFileSync(OUT, 'utf8'); } catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

if (current === generated) {
  console.log(`[build-web-polyfills] verified ${OUT} (${code.length} bytes)`);
} else {
  const temporary = `${OUT}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(temporary, generated, 'utf8');
  try {
    let lastError;
    for (let attempt = 0; attempt < 8; attempt += 1) {
      try {
        fs.renameSync(temporary, OUT);
        lastError = undefined;
        break;
      } catch (error) {
        lastError = error;
        if (!['EACCES', 'EBUSY', 'EPERM', 'UNKNOWN'].includes(error?.code) || attempt === 7) throw error;
        await new Promise((resolve) => setTimeout(resolve, 25 * (attempt + 1)));
      }
    }
    if (lastError) throw lastError;
  } finally {
    try { fs.unlinkSync(temporary); } catch (error) {
      if (error?.code !== 'ENOENT') console.warn(`[build-web-polyfills] temporary cleanup failed: ${error.message}`);
    }
  }
  console.log(`[build-web-polyfills] wrote ${OUT} (${code.length} bytes)`);
}
